#!/bin/sh
# Builds NetSurf's own libraries as static archives, for the phone.
#
# Each library brings a makefile that expects to run the target's own
# binaries; cross-compiling through them means teaching their build system a
# new target. They are small and plain C, so this compiles the sources
# straight out of the tarballs instead. Two of them generate sources from
# tables first: libparserutils and libhubbub with a perl script, libcss with
# a program that is built for the machine doing the building and then run.
#
# Usage: build-netsurf-libs.sh <cc> <ar> <outdir> [extra cflags...]
#   HOSTCC   compiler for the generator libcss needs (default: cc)

set -eu

CC=${1:?compiler}
AR=${2:?archiver}
OUT=${3:?output directory}
shift 3
HOSTCC=${HOSTCC:-cc}

BASE=https://download.netsurf-browser.org/libs/releases

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$OUT" "$WORK/obj"

CFLAGS="-O2 -fPIC -fcommon -DNDEBUG -std=c99 -D_POSIX_C_SOURCE=200809L -D_DEFAULT_SOURCE $*"

fetch() {
    name=$1
    version=$2
    echo "fetching $name $version"
    curl -sSL -o "$WORK/$name-$version.tar.gz" \
        "$BASE/$name-$version-src.tar.gz"
    tar xzf "$WORK/$name-$version.tar.gz" -C "$WORK"
}

# The libraries reach into each other's headers, so all of them are on the
# include path for all of them.
incs_all() {
    result=""
    for d in "$WORK"/lib*/include; do
        [ -d "$d" ] && result="$result -I$d"
    done
    echo "$result"
}

build() {
    name=$1
    version=$2
    shift 2

    root="$WORK/$name-$version"
    incs="-I$root/src -I$root/include $(incs_all)"

    # The generator libcss runs to make its property parsers has a main of
    # its own, so it is not part of the library.
    srcs=$(find "$root/src" -name '*.c' | grep -v css_property_parser_gen.c | sort)
    # libdom's binding to libhubbub is what turns a byte stream into a DOM,
    # and NetSurf asks for it through the public headers.
    if [ -d "$root/bindings/hubbub" ]; then
        srcs="$srcs $(find "$root/bindings/hubbub" -name '*.c' | sort)"
        mkdir -p "$OUT/include/dom/bindings/hubbub"
        cp "$root"/bindings/hubbub/*.h "$OUT/include/dom/bindings/hubbub/"
    fi
    count=$(echo "$srcs" | wc -w)
    echo "building $name $version: $count files"

    objs=""
    for s in $srcs; do
        o="$WORK/obj/$name/$(echo "$s" | sed "s|$root/||; s|/|_|g; s|\.c$|.o|")"
        mkdir -p "$(dirname "$o")"
        $CC $CFLAGS $incs -c "$s" -o "$o"
        objs="$objs $o"
    done

    case $name in
        lib*) archive="$OUT/$name.a" ;;
        *) archive="$OUT/lib$name.a" ;;
    esac
    $AR rcs "$archive" $objs
    echo "  -> $archive ($(wc -c < "$archive") bytes)"
}

for spec in libwapcaplet:0.4.3 libparserutils:0.2.5 libhubbub:0.3.8 \
            libcss:0.9.2 libdom:0.4.2 libnsutils:0.1.1 libnsgif:1.0.0 \
            libnsbmp:0.1.7; do
    fetch "${spec%%:*}" "${spec##*:}"
done

# libparserutils: the charset alias table
( cd "$WORK/libparserutils-0.2.5" && perl build/make-aliases.pl )

# libhubbub: the table of named character references
( cd "$WORK/libhubbub-0.3.8" && perl build/make-entities.pl )

# libhubbub: the element name table, from gperf
( cd "$WORK/libhubbub-0.3.8"
  gperf --output-file=src/treebuilder/autogenerated-element-type.c.tmp \
      src/treebuilder/element-type.gperf
  sed -e 's/^\(const struct element_type_map\)/static \1/' \
      src/treebuilder/autogenerated-element-type.c.tmp \
      > src/treebuilder/autogenerated-element-type.c
  rm src/treebuilder/autogenerated-element-type.c.tmp
)

# libcss: one parser per property, emitted by a program built for the host
( cd "$WORK/libcss-0.9.2"
  $HOSTCC -O2 -o "$WORK/gen_parser" src/parse/properties/css_property_parser_gen.c
  # The property list is what the makefile pulls out of the same file with
  # the same expression: every line that names a property.
  for prop in $(perl -pe'$_="" unless /^([^\#][^:]+):/;$_=$1 . " "' \
        src/parse/properties/properties.gen); do
      line=$(grep "^$prop:" src/parse/properties/properties.gen)
      "$WORK/gen_parser" -o "src/parse/properties/autogenerated_$prop.c" "$line"
  done
)

build libwapcaplet 0.4.3
build libnsutils 0.1.1
build libnsgif 1.0.0
build libnsbmp 0.1.7
build libparserutils 0.2.5
build libhubbub 0.3.8
build libcss 0.9.2
build libdom 0.4.2

# A single include tree, so whatever builds on top of these needs one -I.
for d in "$WORK"/lib*/include; do
    [ -d "$d" ] && cp -R "$d"/. "$OUT/include"/
done

echo
echo "archives in $OUT:"
ls -l "$OUT"
